def day_of_week(n: int) -> str:
    days = {
        1: "Понедельник",
        2: "Вторник",
        3: "Среда",
        4: "Четверг",
        5: "Пятница",
        6: "Суббота",
        7: "Воскресенье"
    }
    return days.get(n, "Ошибка: нужно число от 1 до 7")

if __name__ == "__main__":
    n = int(input("Введите число от 1 до 7: "))
    print(day_of_week(n))
